# 1. DOMAIN ENUMS & FORMAL TAXONOMIES
# ============================================================================

class MachineType(str, Enum):
    """Product variant types indicating quality variant and load tolerances."""
    L = "L"  # Low quality variant (60% of production volume, 6,000 samples)
    M = "M"  # Medium quality variant (30% of production volume, 2,997 samples)
    H = "H"  # High quality variant (10% of production volume, 1,003 samples)


class FailureMode(str, Enum):
    """Formal taxonomy of machine failure modes based on physical mechanisms."""
    NONE = "No Failure"
    TWF = "Tool Wear Failure"        # Tool wear limit reached (~200-240 min)
    HDF = "Heat Dissipation Failure" # Inadequate heat transfer (temp diff < 8.6K and speed < 1380 rpm)
    PWF = "Power Failure"            # Mechanical power out of safe envelope (<3500W or >9000W)
    OSF = "Overstrain Failure"       # Combined load of torque and tool wear exceeds structural limit
    RNF = "Random Failure"           # Uncorrelated random electrical/mechanical failure (~0.1%)


class ActionSeverity(str, Enum):
    """Urgency / priority classification of maintenance interventions."""
    INFO = "Routine Informational"
    LOW = "Low Urgency (Scheduled Next Cycle)"
    MEDIUM = "Medium Urgency (Schedule Promptly)"
    HIGH = "High Urgency (Prioritize Shift Maintenance)"
    CRITICAL = "Critical Urgency (Immediate Safe Shutdown)"


