# 3. FORMAL ENTITY DEFINITIONS (FRAME-BASED KNOWLEDGE MODEL)
# ============================================================================

@dataclass
class Machine:
    """Frame representing an industrial asset."""
    udi: int
    product_id: str
    machine_type: MachineType
    name: str = "CNC Milling Station"
    operational_status: str = "Active"

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class SensorReading:
    """Frame representing instantaneous physical observations."""
    air_temperature_k: float
    process_temperature_k: float
    rotational_speed_rpm: float
    torque_nm: float
    tool_wear_min: float
    timestamp: str = field(default_factory=lambda: datetime.datetime.now().isoformat())

    @property
    def temperature_difference_k(self) -> float:
        """Physical thermal delta driving convective heat dissipation."""
        return self.process_temperature_k - self.air_temperature_k

    @property
    def mechanical_power_w(self) -> float:
        """Calculated shaft power in Watts: P = (2 * pi / 60) * Speed * Torque."""
        return (2.0 * 3.141592653589793 / 60.0) * self.rotational_speed_rpm * self.torque_nm

    @property
    def overstrain_index(self) -> float:
        """Product of tool wear and torque representing cutting strain."""
        return self.tool_wear_min * self.torque_nm

    def to_dict(self) -> Dict[str, Any]:
        d = asdict(self)
        d["temperature_difference_k"] = round(self.temperature_difference_k, 2)
        d["mechanical_power_w"] = round(self.mechanical_power_w, 2)
        d["overstrain_index"] = round(self.overstrain_index, 2)
        return d


@dataclass
class OperatingCondition:
    """Derived physical state classifying regime and environmental strain."""
    thermal_strain_level: str    # "Normal", "Elevated", "Critical Heat Dissipation Risk"
    power_regime: str            # "Underload", "Nominal", "Overload Risk"
    wear_condition: str          # "Fresh Tool", "Moderate Wear", "Near Failure Limit"
    overall_stress_state: str    # "Optimal", "Strained", "High Risk"


@dataclass
class PredictedFailureRisk:
    """Model output frame quantifying predictive likelihood."""
    failure_predicted: bool
    failure_probability: float
    confidence_level: str        # "High Confidence Normal", "Borderline", "High Confidence Failure"
    model_name: str
    model_version: str = "v1.0.0"


@dataclass
class MaintenanceAction:
    """Standardized maintenance intervention task."""
    action_code: str
    title: str
    description: str
    estimated_duration_min: int
    severity: ActionSeverity
    prerequisites: List[str] = field(default_factory=list)


@dataclass
class MaintenanceRecommendation:
    """
    Formal synthesis connecting machine state, model prediction, and decision rules.
    """
    action: MaintenanceAction
    reasoning: str
    triggered_rules: List[str]
    is_safe_to_operate: bool
    recommended_timeframe: str
    model_risk_score: float

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action_code": self.action.action_code,
            "title": self.action.title,
            "severity": self.action.severity.value,
            "reasoning": self.reasoning,
            "triggered_rules": self.triggered_rules,
            "is_safe_to_operate": self.is_safe_to_operate,
            "recommended_timeframe": self.recommended_timeframe,
            "model_risk_score": round(self.model_risk_score, 4),
            "estimated_duration_min": self.action.estimated_duration_min
        }


