@dataclass
class ValidationResult:
    """Structured response from domain validation checks."""
    is_valid: bool
    errors: List[str] = field(default_factory=list)
    warnings: List[str] = field(default_factory=list)
    validated_data: Dict[str, Any] = field(default_factory=dict)

    def summary(self) -> str:
        if self.is_valid:
            return "Validation Succeeded: All attributes satisfy domain schema and physical constraints."
        return f"Validation Failed: {len(self.errors)} error(s) found. [{', '.join(self.errors)}]"


def validate_machine_input(input_dict: Dict[str, Any]) -> ValidationResult:
    """
    Validates a machine record against formal schema and dataset constraints:
    - Verifies required attributes are present.
    - Validates data types.
    - Validates categorical membership (e.g. Type in ['L', 'M', 'H']).
    - Validates physical numerical ranges (Air temp, Process temp, Speed, Torque, Wear).
    - Checks cross-feature physical plausibility (Process Temp >= Air Temp).
    """
    errors: List[str] = []
    warnings: List[str] = []
    validated: Dict[str, Any] = {}

    # Check for required fields
    required_fields = [
        "Type",
        "Air temperature [K]",
        "Process temperature [K]",
        "Rotational speed [rpm]",
        "Torque [Nm]",
        "Tool wear [min]"
    ]

    for req in required_fields:
        if req not in input_dict or input_dict[req] is None:
            errors.append(f"Missing required attribute: '{req}'.")

    if errors:
        return ValidationResult(is_valid=False, errors=errors, warnings=warnings, validated_data={})

    # Validate 'Type'
    raw_type = str(input_dict["Type"]).strip().upper()
    if raw_type not in ["L", "M", "H"]:
        errors.append(f"Invalid categorical value for 'Type': '{input_dict['Type']}'. Must be one of ['L', 'M', 'H'].")
    else:
        validated["Type"] = raw_type

    # Validate numerical features against constraints
    for feat_name in ["Air temperature [K]", "Process temperature [K]", "Rotational speed [rpm]", "Torque [Nm]", "Tool wear [min]"]:
        raw_val = input_dict.get(feat_name)
        spec = SENSOR_CONSTRAINTS[feat_name]

        try:
            val_float = float(raw_val)
        except (ValueError, TypeError):
            errors.append(f"Attribute '{feat_name}' must be numeric; received '{raw_val}'.")
            continue

        if val_float < spec["min"] or val_float > spec["max"]:
            errors.append(
                f"Attribute '{feat_name}' value {val_float} is out of permitted range "
                f"[{spec['min']}, {spec['max']}] {spec['unit']}."
            )
        else:
            validated[feat_name] = val_float

    # Cross-attribute physical consistency check
    if "Air temperature [K]" in validated and "Process temperature [K]" in validated:
        if validated["Process temperature [K]"] < validated["Air temperature [K]"]:
            warnings.append(
                f"Process temperature ({validated['Process temperature [K]']} K) is below "
                f"Air temperature ({validated['Air temperature [K]']} K). While thermodynamically "
                "possible with refrigeration, normal milling operation dissipates heat outward."
            )

    is_valid = (len(errors) == 0)
    return ValidationResult(is_valid=is_valid, errors=errors, warnings=warnings, validated_data=validated if is_valid else {})


def validate_recommendation_consistency(
    risk: PredictedFailureRisk,
    recommendation: MaintenanceRecommendation
) -> Tuple[bool, Optional[str]]:
    """
    Verifies that the recommended action semantically aligns with the predicted risk level.
    Prevents absurdities like recommending immediate shutdown for a 0.01% risk normal asset,
    or routine monitoring for a 99% risk failure state.
    """
    if risk.failure_probability >= 0.70:
        if recommendation.is_safe_to_operate:
            return False, "Inconsistent: High failure risk (>= 0.70) cannot declare asset safe to operate."
        if recommendation.action.severity in [ActionSeverity.INFO, ActionSeverity.LOW]:
            return False, "Inconsistent: High failure risk (>= 0.70) cannot have low/info severity action."

    if risk.failure_probability < 0.20:
        if recommendation.action.severity == ActionSeverity.CRITICAL:
            return False, "Inconsistent: Low failure risk (< 0.20) should not trigger emergency shutdown."

    return True, None


